const ZIP_TO_TERRITORY = new Map<string, string>();
for (const t of territories) for (const z of t.zip_codes) ZIP_TO_TERRITORY.set(z, t.id);

/** Maps a property ZIP to a service territory — the first input to matching. */
export function territoryForZip(zip: string): string | null {
  return ZIP_TO_TERRITORY.get(zip.trim()) ?? null;
}

export function territoryName(id: string | null): string {
  if (!id) return 'Unassigned';
  return territories.find((t) => t.id === id)?.name ?? 'Unknown';
}

